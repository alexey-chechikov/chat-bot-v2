def recall(S, legs, tol=36):
    t = S.t
    ok, rows = 0, []
    for day, act, word in MARKS:
        x = lc.T(day) + 12 * 3600
        side = 1 if act[-1] == "L" else -1
        cand = [t[le[1] if act.startswith("x") else le[0]] for le in legs if le[4] == side]
        best = min(cand, key=lambda z: abs(z - x)) if cand else x + 10 ** 9
        hit = abs(best - x) / 3600 <= tol
        ok += hit
        rows.append((day, act, hit))
    return ok, rows


def win_sums(S, legs):
    r = lc.nets(S, legs)
    t0 = S.t[[x[0] for x in legs]]
    return [round(float(r[(t0 >= lc.T(a)) & (t0 < lc.T(z))].sum()), 1) for _, a, z in WIN]


