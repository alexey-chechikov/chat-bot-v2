def dictionary(cols):
    out = []
    for c in cols:
        if c.startswith("_"):
            continue
        d = BASIC.get(c) or next((v for k, v in sorted(DESC, key=lambda kv: -len(kv[0])) if c.startswith(k)), "")
        out.append({"столбец": c, "что значит": d})
    return pd.DataFrame(out)


def main():
    a, f, h4f = sc.load_coin("BTC")
    lay = pl.layer(a)
    bs = [x for x in wl.series() if x[0] == "Bitstamp"][0]
    b, layb = bs[1], pl.layer(bs[1])
    X1, y1 = check_m2(a, lay)
    X2, y2 = check_m2(b, layb)
    save_m2(np.vstack([X1, X2]), np.r_[y1, y2])
    D = pd.concat([build("Binance", a, lay, h4f), build("Bitstamp", b, layb, None)], ignore_index=True)
    D.to_pickle(OUT / "trade_table_btc.pkl")
    (OUT / "live_features.json").write_text(json.dumps(sorted(LIVE_KEYS), ensure_ascii=False, indent=0))
    vis = D[[c for c in D.columns if not c.startswith("_")]]
    vis.to_csv(OUT / "trade_table_btc.csv", sep=";", decimal=",", index=False, encoding="utf-8-sig", float_format="%.4f")
    dictionary(D.columns).to_csv(OUT / "trade_features_dictionary.csv", sep=";", index=False, encoding="utf-8-sig")
    print(f"таблица: {len(D)} сделок, {vis.shape[1]} столбцов → {OUT / 'trade_table_btc.csv'}", flush=True)
    print(D.groupby(["ряд", "стратегия", "тип"])["итог, % базы"].agg(["size", "sum", "mean"]).round(2).to_string(), flush=True)


if __name__ == "__main__":
    main()
