def utc(ts):
    return datetime.fromtimestamp(int(ts), timezone.utc).strftime("%Y-%m-%d %H:%M")


def intervals(ev):
    return [(e["pos"]["entry_i"], e["i"], e["side"]) for e in ev if e["kind"] == "выход"]


def side_at(iv, i):
    for i0, i1, s in iv:
        if i0 <= i < i1:
            return s
    return 0


def build(name, a, lay, h4f):
    P = fx.prepare(a, lay, h4f)
    XT = fe.ext_prepare(a, name)
    ev, _ = en.simulate(a, lay)
    ev432, _, _ = en.simulate432(a)
    iv_sys, iv_432 = intervals(ev), intervals(ev432)
    rows = []
    for strat, E in (("система", ev), ("432", ev432)):
        prev = []
        for e in [x for x in E if x["kind"] == "выход"]:
            p = e["pos"]
            i0, i1, s = p["entry_i"], e["i"], e["side"]
            add_t = p.get("add_t") if p["add_done"] and e["tag"] in en.MAIN else None
            add_i = int(np.searchsorted(a["t"], add_t)) if add_t is not None else None
            if add_i is not None and (add_i >= len(a["t"]) or a["t"][add_i] != add_t):
                add_i = None
            r = {"ряд": name, "стратегия": strat, "тип": f"{'лонг' if s == 1 else 'шорт'} {e['tag']}", "сторона": s, "вход UTC": utc(p["entry_t"]), "выход UTC": utc(e["t"]),
                 "цена входа": p["entry"], "цена выхода": e["px"], "вес": p["w"], "добор": float(bool(p["add_done"]) and e["tag"] in en.MAIN),
                 "цена добора": p["add_px"], "добор UTC": utc(add_t) if add_t is not None else None,
                 "причина выхода": e["why"], "итог, % базы": e["res"], "ход, %": s * (e["px"] / p["entry"] - 1) * 100,
                 "_i0": i0, "_i1": i1, "_t0": p["entry_t"], "_t1": e["t"], "_add_t": add_t, "_add_i": add_i,
                 "_add_before_close": bool(add_t is not None)}
            r.update(fx.path(a, i0, i1, s, p["entry"], e["px"], exit_mode="target" if e["why"].startswith("цель") else "close"))
            r.update({k: bool(v[i0]) for k, v in P.items() if k.startswith("_funding_coverage_")})
            r.update(fx.history(prev, p["entry_t"], s))
            r["432 в позиции"] = float(side_at(iv_432, i0) != 0) if strat == "система" else None
            r["система в позиции"] = float(side_at(iv_sys, i0)) if strat == "432" else None
            live = fx.row(P, a, i0)
            live.update(fx.history(prev, p["entry_t"], s))
            LIVE_KEYS.update(live)
            r.update(fx.row(P, a, i0))
            r.update({k: (float(v[i0]) if np.isfinite(v[i0]) else None) for k, v in XT.items()})
            rows.append(r)
            prev.append((p["entry_t"], e["t"], s, e["res"]))
    return pd.DataFrame(rows)


def check_m2(a, lay):
    """features.m2_vector против flat_1109.positions на всех позициях системы."""
    ref = fl.positions(a, lay)
    ev, _ = en.simulate(a, lay)
    X = [e for e in ev if e["kind"] == "выход"]
    al = fx.align(a)
    prev, mine = 0.0, []
    for e in X:
        mine.append(fx.m2_vector(a, lay, e["pos"]["entry_i"], e["side"], e["tag"], prev, al))
        prev = e["res"]
    d = np.abs(np.vstack(mine) - np.vstack(ref["x"])).max()
    print(f"M2: признаки службы против flat_1109 — позиций {len(mine)}, наибольшее расхождение {d:.2e}", flush=True)
    assert d < 1e-9
    return np.vstack(mine), np.array([e["res"] for e in X])


def save_m2(X, y):
    lo, hi = np.quantile(y, [0.05, 0.95])
    s = StandardScaler().fit(X)
    md = Ridge(alpha=10.0).fit(s.transform(X), np.clip(y, lo, hi))
    pred = md.predict(s.transform(X))
    m = {"what": "M2 flat_1109b: Ridge alpha=10 на итоге позиции (обрезан 5–95%), 25 признаков features.M2_FEATS; обучен на Binance 2018–26 и Bitstamp 2014–17. "
                 "Только тень: размер 0.5 + ранг не доказан (плацебо 0.058 / 0.123).",
         "built": utc(datetime.now(timezone.utc).timestamp()), "n": int(len(y)), "feats": fx.M2_FEATS, "mean": s.mean_.tolist(), "scale": s.scale_.tolist(),
         "coef": md.coef_.tolist(), "intercept": float(md.intercept_), "train_sorted": np.sort(pred).round(6).tolist()}
    fx.M2_PATH.write_text(json.dumps(m, ensure_ascii=False, indent=1))
    print(f"M2 сохранена: {fx.M2_PATH}, сделок {len(y)}", flush=True)
    return m


